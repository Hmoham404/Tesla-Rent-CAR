export const dictionaries = { fr, en, it, es, tn };
const LanguageContext = createContext<{
  lang: Language;
  setLang: (lang: Language) => void;
  t: Copy;
}>({ lang: "fr", setLang: () => {}, t: fr });
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLanguage] = useState<Language>(() => {
    try {
      const value = localStorage.getItem("tesla-language");
      return languages.some((l) => l.code === value)
        ? (value as Language)
        : "fr";
    } catch {
      return "fr";
    }
  });
  const setLang = (value: Language) => {
    setLanguage(value);
    try {
      localStorage.setItem("tesla-language", value);
    } catch {
      /* Selection remains usable without storage. */
    }
  };
  useEffect(() => {
    document.documentElement.lang = languages.find(
      (l) => l.code === lang,
    )!.html;
    document.documentElement.dir = lang === "tn" ? "rtl" : "ltr";
    document.title = `TESLA Rent Car — ${dictionaries[lang].top}`;
  }, [lang]);
  return (
    <LanguageContext.Provider value={{ lang, setLang, t: dictionaries[lang] }}>
      {children}
    </LanguageContext.Provider>
  );
}
export const useLanguage = () => useContext(LanguageContext);
